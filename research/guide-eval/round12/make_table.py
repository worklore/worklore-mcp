#!/usr/bin/env python3
"""Round 12 tables from runs/*/grade.json + meta.json. Repetition 0 (smoke runs) is left out.
python3 make_table.py > results.md
Per task: PASS / runs for every agent x language x arm, then "landed on the old package" (WORKS_ON_OLD), searched the
web (real tool calls), median wall time and tokens where the log has them."""
import glob, json, os, re, statistics, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from web_use import web_calls

D = os.path.dirname(os.path.abspath(__file__))
AGENTS = ["claude-haiku", "codex-sol-low", "kimi-k31", "claude-deepseek"]
NAMES = {"claude-haiku": "Claude Code · Haiku 5.5", "codex-sol-low": "Codex · GPT-6-Sol low",
         "kimi-k31": "Kimi Code · K3.1 Pro", "claude-deepseek": "Claude Code · DeepSeek V4.1 Flash"}
LANGS = ["en", "ru", "uk", "es"]
ARMS = ["none", "line", "story"]
TASKS = {"h": "Hedera: update the SDK (current = @hiero-ledger/sdk)", "p": "Prisma: upgrade to the current version (= Prisma 8)",
         "p8": "Prisma, target named: upgrade to version 8"}

def tokens(R, agent):
    """(input incl. cache reads, output) from the log, or None."""
    try: log = open(os.path.join(R, "agent.log"), errors="ignore").read()
    except OSError: return None
    if agent.startswith("claude"):
        for line in reversed(log.splitlines()):
            if '"type":"result"' in line:
                try: u = json.loads(line).get("usage") or {}
                except ValueError: return None
                return (u.get("input_tokens", 0) + u.get("cache_read_input_tokens", 0) + u.get("cache_creation_input_tokens", 0),
                        u.get("output_tokens", 0))
    if agent.startswith("codex"):
        i = o = 0; seen = False
        for line in log.splitlines():
            if '"turn.completed"' in line:
                try: u = json.loads(line).get("usage") or {}
                except ValueError: continue
                i += u.get("input_tokens", 0); o += u.get("output_tokens", 0); seen = True
        return (i, o) if seen else None
    return None

rows = []
for g in glob.glob(os.path.join(D, "runs", "*", "grade.json")):
    R = os.path.dirname(g)
    try: m = json.load(open(os.path.join(R, "meta.json"))); gr = json.load(open(g))
    except (OSError, ValueError): continue
    if m.get("rep", 0) == 0 or m.get("limit"): continue
    old = gr.get("WORKS_ON_OLD_SDK") if m["task"] == "h" else gr.get("WORKS_ON_PRISMA7")
    rows.append(dict(task=m["task"], lang=m["lang"], agent=m["agent"], arm=m["arm"], rep=m["rep"], PASS=bool(gr.get("PASS")),
                     OLD=bool(old), web=web_calls(R, m["agent"]) > 0, wall=m.get("wall_s"), tok=tokens(R, m["agent"]),
                     infra=gr.get("infra_error")))

def cell(rs, key):
    return f"{sum(r[key] for r in rs)}/{len(rs)}" if rs else "·"

out = ["# Round 12 results (generated by make_table.py; repetition 0 = smoke, not counted)", "",
       f"{len(rows)} graded runs. Cells: PASS / runs. Columns: language, arm (none = task alone, line = 4 lines in AGENTS.md, story = private worklore story as a colleague's note).", ""]
for t, title in TASKS.items():
    out += [f"## {title}", "", "| Agent | " + " | ".join(f"{l} {a}" for l in LANGS for a in ARMS if not (a == "story" and l in ("uk", "es"))) + " |",
            "|---|" + "---|" * 10]
    for key, label in (("PASS", "PASS"), ("OLD", "stayed on the old package, but working"), ("web", "searched the web")):
        if key != "PASS": out += [f"| **{label}** |" + " |" * 10]
        for a in AGENTS:
            cells = []
            for l in LANGS:
                for arm in ARMS:
                    if arm == "story" and l in ("uk", "es"): continue
                    cells.append(cell([r for r in rows if r["task"] == t and r["agent"] == a and r["lang"] == l and r["arm"] == arm], key))
            out.append(f"| {NAMES[a]} | " + " | ".join(cells) + " |")
    out.append("")
    out += ["Median wall time (s) and tokens in/out per run, all cells of this task:", ""]
    for a in AGENTS:
        rs = [r for r in rows if r["task"] == t and r["agent"] == a]
        if not rs: continue
        w = statistics.median([r["wall"] for r in rs if r["wall"] is not None]) if rs else None
        tk = [r["tok"] for r in rs if r["tok"]]
        ts = f"{int(statistics.median(x[0] for x in tk)):,} in / {int(statistics.median(x[1] for x in tk)):,} out" if tk else "not in log"
        out.append(f"- {NAMES[a]}: {len(rs)} runs, median {w:.0f} s, {ts}")
    out.append("")
inf = [r for r in rows if r["infra"]]
if inf: out += [f"Infra errors (redo): {len(inf)}", ""]
print("\n".join(out))
